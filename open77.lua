-- op77_map3d: a 3D city map and minimap built from the game's own 3D map (the
-- buildings, roads, terrain and landmarks of base\entities\cameras\3dmap) and its
-- traffic network (GPS), drawn by NativeUI (the client's own D3D12 scene layer, no
-- browser).
-- It replaces the game's map and minimap while it runs. Blips, waypoint, GPS route,
-- areas (polygons), theme and behaviour are an API for any resource (README.md).
--
-- Client: the native map (client/native, ui/native), the player feed, blips, areas,
--         waypoint, exports.
-- Server: blips for everyone / a player / a list, waypoint and map for a player.
-- Data:   web/data, generated by tools/export_web.py from the game files.
resource "op77_map3d"
version "0.3.0"
open77_version ">=0.0.1"
auto_start true
-- The client owns a NativeUI document and its GPU scene: reconnect rather than live reload.
reload_policy "reconnect"

shared_script "shared/config.lua"
shared_script "shared/blip.lua"
shared_script "shared/jam.lua"
shared_script "shared/area.lua"
shared_script "shared/influence.lua"

server_script "server/main.lua"

client_script "client/native/defaults.lua"
client_script "client/native/theme.lua"
client_script "client/native/icons.lua"
client_script "client/native/app.lua"
client_script "client/main.lua"

files {
    "ui/native/map.rml",
    "ui/native/map.rcss",
    "ui/native/fonts/*",
    "web/data/*",
}

permissions {
    -- both sides: server blips, waypoint and map requests
    "network.events",
    -- client
    "input.actions",     -- the game's own map key/menu is blocked while this map runs
    "ui.vanilla.hud",    -- the vanilla minimap is hidden
    "ui.vanilla.map",    -- the waypoint is mirrored to the game's (Open77.blips)
    "players.read",      -- other players near you, shown as blips
    "vehicles.read",     -- the arrow follows the car's nose, not its motion (reversing)
}
